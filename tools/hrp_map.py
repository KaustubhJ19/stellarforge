"""HRP risk map (Spec 5, ticket 07): which of NASA's 17 HRP risks the tool covers, and which it does not.

Built only from content/cards/*.json, so the map can claim a risk only when a card names it.
The 17 titles come from content_lint.HRP_RISKS (https://www.nasa.gov/hrp/risks/, read 2026-11-15).

Command line:
    python tools/hrp_map.py   # rewrites docs/hrp-risk-map.md
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

from content_lint import HRP_RISKS, UNCOVERED  # noqa: E402

CARDS = ROOT / "content" / "cards"
OUT = ROOT / "docs" / "hrp-risk-map.md"
SOURCE = "https://www.nasa.gov/hrp/risks/"


def build(cards_dir=CARDS):
    """Return {covered: {risk: [{card, indicators}]}, uncovered: [risk], cards_without_risk: [{card, reason}]}."""
    covered, without = {}, []
    for path in sorted(Path(cards_dir).glob("*.json")):
        card = json.loads(path.read_text(encoding="utf-8"))
        name = f"content/cards/{path.name}"
        why = card["why"]
        risk = why["hrp_risk"]
        if risk == UNCOVERED:
            without.append({"card": name, "reason": why["uncovered_reason"]})
            continue
        if risk not in HRP_RISKS:
            raise ValueError(f"{name}: {risk!r} is not a NASA HRP risk title")
        indicators = [card["indicator"], *card.get("related_indicators", [])]
        covered.setdefault(risk, []).append({"card": name, "indicators": indicators})
    return {
        "covered": dict(sorted(covered.items())),
        "uncovered": sorted(HRP_RISKS - set(covered)),
        "cards_without_risk": without,
    }


def render(m):
    total = len(m["covered"]) + len(m["uncovered"])
    lines = [
        "# NASA HRP risk map",
        "",
        "<!-- Generated by tools/hrp_map.py from content/cards/*.json. Do not edit by hand. -->",
        "",
        f"NASA's Human Research Program lists {total} risks to crew health and performance: {SOURCE} (read 2026-11-15).",
        f"This tool covers {len(m['covered'])} of them through its measurement cards and does not cover the other "
        f"{len(m['uncovered'])}.",
        "",
        "\"Covered\" means a measurement card watches an Indicator linked to the risk and tells the crew what to do "
        "if it is abnormal. It does not mean the tool prevents or diagnoses the risk. Decision support, not diagnosis.",
        "",
        "## Risks the tool covers",
        "",
        "| HRP risk | Indicator(s) | Card(s) |",
        "|---|---|---|",
    ]
    for risk, entries in m["covered"].items():
        indicators = ", ".join(f"`{i}`" for e in entries for i in e["indicators"])
        cards = ", ".join(f"[`{e['card']}`](../{e['card']})" for e in entries)
        lines.append(f"| {risk} | {indicators} | {cards} |")
    lines += ["", "## Risks the tool does not cover", ""]
    lines += [f"- {risk}" for risk in m["uncovered"]]
    lines += [
        "",
        "## Cards that do not map to an HRP risk",
        "",
        "These cards are tracked for crew safety but no HRP risk names their Indicator.",
        "",
        "| Card | Reason |",
        "|---|---|",
    ]
    lines += [f"| [`{e['card']}`](../{e['card']}) | {e['reason']} |" for e in m["cards_without_risk"]]
    return "\n".join(lines) + "\n"


def main():
    OUT.write_text(render(build()), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
