"""Write the human review sheet for a protocol (Spec 1): each step next to the evidence-pack quote it cites.

    python tools/review_sheet.py <protocol-id> [...]   # writes docs/review/<protocol-id>.md

The reviewer marks Accept / Edit / Reject per step, then approves accepted steps with
tools/approve_steps.py. This tool only reads content; it never changes a step.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import lint_content as lc  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "review"


def _cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def render(doc: dict, pack: dict | None, approvers: set[str]) -> str:
    lines = [
        f"# Review sheet: {doc['title']}",
        "",
        f"Protocol `{doc['id']}`. Generated by `tools/review_sheet.py` from the protocol and its evidence pack; "
        "do not edit by hand, regenerate it.",
        "Decision support, not diagnosis. Check each step against the quoted section, not against general practice.",
        "",
        "| Step | Status | Step text | Cited section | Guideline quote | Accept / Edit / Reject |",
        "|---|---|---|---|---|---|",
    ]
    for s in doc["steps"]:
        problem = lc.approval_problem(s, approvers)
        if not problem:
            status = f"approved by {s['approved_by']} on {s['approved_on']}"
        elif s.get("status") == lc.DRAFT:
            status = f"draft ({s.get('drafted_by', 'drafter not recorded')})"
        elif s.get("status") is None:
            status = "awaiting review (no status)"
        else:
            status = f"awaiting review: {problem}"
        rec = lc.pack_entry(pack, s.get("source"))
        quote = " / ".join(rec.get("quotes") or [rec.get("kind", "")]) if rec else "**not in evidence pack**"
        lines.append(f"| `{s['id']}` | {_cell(status)} | {_cell(s['text'])} | {_cell(s['source']['section'])} "
                     f"| {_cell(quote)} | ☐ |")
    lines += ["", "Reviewer name:", "", "Date:", ""]
    return "\n".join(lines)


def main(argv) -> int:
    content = ROOT / "content"
    approvers = lc.load_approvers(content / "approvers.json")
    OUT.mkdir(parents=True, exist_ok=True)
    for pid in argv[1:]:
        doc = json.loads((content / "protocols" / f"{pid}.json").read_text(encoding="utf-8"))
        pack = lc.load_pack(content, pid)
        out = OUT / f"{pid}.md"
        out.write_text(render(doc, pack, approvers), encoding="utf-8")
        print(f"wrote {out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
