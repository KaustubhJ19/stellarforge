"""Credits page text (Spec 5, ticket 10): docs/credits.md, generated from content/credits.json.

content/credits.json is the source of truth (the app can read it directly); this page is for the write-up.

Command line:
    python tools/credits_page.py   # rewrites docs/credits.md
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CREDITS = ROOT / "content" / "credits.json"
OUT = ROOT / "docs" / "credits.md"


def _cell(text):
    return text.replace("|", "\\|")


def render(doc):
    lines = [
        "# Credits",
        "",
        "<!-- Generated by tools/credits_page.py from content/credits.json. Do not edit by hand. -->",
        "",
        f"Every dataset, model and asset StellarForge uses, with its source and licence (checked {doc['checked']}).",
        "",
        "| Name | Kind | Licence | Used for |",
        "|---|---|---|---|",
    ]
    for e in doc["entries"]:
        licence = f"[{e['licence']}]({e['licence_url']})" if e.get("licence_url") else e["licence"]
        if e.get("restriction"):
            licence += f". **Restriction:** {e['restriction']}"
        lines.append(f"| [{_cell(e['name'])}]({e['link']}) | {e['kind']} | {_cell(licence)} | {_cell(e['used_for'])} |")
    cites = [e for e in doc["entries"] if e.get("citation")]
    if cites:
        lines += ["", "## Citations", ""]
        lines += [f"- {e['name']}: {e['citation']}" for e in cites]
    return "\n".join(lines) + "\n"


def main():
    OUT.write_text(render(json.loads(CREDITS.read_text(encoding="utf-8"))), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
